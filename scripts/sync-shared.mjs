// Copies the shared safety code (packages/shared/src) into supabase/functions/_shared/vendor, because
// Edge Functions are deployed from supabase/functions and may not bundle files outside it (PLAN.md 5.5).
//   node scripts/sync-shared.mjs           write the copies
//   node scripts/sync-shared.mjs --check   fail if a copy is out of date (npm test runs this)
//
// packages/shared is the only place to edit. Each copy says so in its first line.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const from = join(root, "packages", "shared", "src");
const to = join(root, "supabase", "functions", "_shared", "vendor");
const MODULES = ["redflags", "pii", "consent", "labs"];

function copies() {
  const out = [];
  for (const name of MODULES) {
    const header = `// GENERATED by scripts/sync-shared.mjs from packages/shared/src/${name}`;
    // @ts-self-types tells Deno where the types are; Node and browsers ignore the comment.
    const js = `${header}.js. Do not edit.\n// @ts-self-types="./${name}.d.ts"\n${readFileSync(join(from, `${name}.js`), "utf8")}`;
    const dts = `${header}.d.ts. Do not edit.\n${readFileSync(join(from, `${name}.d.ts`), "utf8")}`;
    out.push([`${name}.js`, js], [`${name}.d.ts`, dts]);
  }
  return out;
}

const check = process.argv.includes("--check");
let stale = 0;
if (!check) mkdirSync(to, { recursive: true });
for (const [file, content] of copies()) {
  const path = join(to, file);
  if (check) {
    if (!existsSync(path) || readFileSync(path, "utf8") !== content) {
      console.error(`out of date: supabase/functions/_shared/vendor/${file} (run: node scripts/sync-shared.mjs)`);
      stale += 1;
    }
  } else {
    writeFileSync(path, content);
    console.log(`wrote supabase/functions/_shared/vendor/${file}`);
  }
}
if (check) process.exit(stale ? 1 : 0);
